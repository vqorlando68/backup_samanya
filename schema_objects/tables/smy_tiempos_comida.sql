CREATE TABLE SMY_TIEMPOS_COMIDA 
   (	"ID" NUMBER NOT NULL ENABLE, 
	"CODIGO" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NOMBRE" VARCHAR2(100) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DESCRIPCION" VARCHAR2(300) COLLATE "USING_NLS_COMP", 
	"HORA_SUGERIDA" VARCHAR2(10) COLLATE "USING_NLS_COMP", 
	"ORDEN" NUMBER DEFAULT 1 NOT NULL ENABLE, 
	"ESTADO" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'ACTIVO' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	 CONSTRAINT "CK_SMY_TIEMPOS_ESTADO" CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')) ENABLE, 
	 CONSTRAINT "PK_SMY_TIEMPOS_COMIDA" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_TIEMPOS_COMIDA_COD" UNIQUE ("CODIGO")
  USING INDEX  ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
