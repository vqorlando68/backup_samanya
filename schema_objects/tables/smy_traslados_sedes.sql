CREATE TABLE SMY_TRASLADOS_SEDES 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"CODIGO_TRASLADO" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"ID_CENTRO_ORIGEN" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CENTRO_DESTINO" NUMBER(10,0) NOT NULL ENABLE, 
	"FECHA_ENVIO" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"FECHA_RECEPCION" DATE, 
	"ESTADO_TRASLADO" VARCHAR2(30) COLLATE "USING_NLS_COMP" DEFAULT 'EN_TRANSITO' NOT NULL ENABLE, 
	"ID_USUARIO_DESPACHA" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_USUARIO_RECIBE" NUMBER(10,0), 
	"NOTAS_DESPACHO" VARCHAR2(400) COLLATE "USING_NLS_COMP", 
	"NOTAS_RECEPCION" VARCHAR2(400) COLLATE "USING_NLS_COMP", 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_TRS_DIFF" CHECK (ID_CENTRO_ORIGEN <> ID_CENTRO_DESTINO) ENABLE, 
	 CONSTRAINT "CK_SMY_TRS_ESTADO" CHECK (ESTADO_TRASLADO IN ('EN_TRANSITO', 'RECIBIDO_CONFORME', 'RECIBIDO_CON_NOVEDAD', 'CANCELADO')) ENABLE, 
	 CONSTRAINT "PK_SMY_TRASLADOS" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_TRS_COD" UNIQUE ("CODIGO_TRASLADO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_TRS_ORIGEN" FOREIGN KEY ("ID_CENTRO_ORIGEN")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_TRS_DESTINO" FOREIGN KEY ("ID_CENTRO_DESTINO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_TRS_USUDESP" FOREIGN KEY ("ID_USUARIO_DESPACHA")
	  REFERENCES "SMY_USUARIOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_TRS_USUREC" FOREIGN KEY ("ID_USUARIO_RECIBE")
	  REFERENCES "SMY_USUARIOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
