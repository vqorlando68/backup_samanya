CREATE TABLE SMY_REGISTROS_ALIMENTACION 
   (	"ID" NUMBER NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER NOT NULL ENABLE, 
	"ID_RESIDENTE" NUMBER NOT NULL ENABLE, 
	"FECHA" DATE NOT NULL ENABLE, 
	"ID_TIEMPO_COMIDA" NUMBER NOT NULL ENABLE, 
	"ID_PLAN_NUTRICIONAL" NUMBER, 
	"PORCENTAJE_INGESTA" NUMBER DEFAULT 0 NOT NULL ENABLE, 
	"LIQUIDOS_ML" NUMBER DEFAULT 0, 
	"TOLERANCIA" VARCHAR2(30) COLLATE "USING_NLS_COMP" DEFAULT 'BUENA', 
	"ASISTIO" VARCHAR2(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"OBSERVACIONES" VARCHAR2(1000) COLLATE "USING_NLS_COMP", 
	"ID_EMPLEADO_REGISTRA" NUMBER, 
	"CREADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP" DEFAULT 'SISTEMA' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ACTUALIZADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP", 
	"FECHA_ACTUALIZACION" DATE, 
	 CONSTRAINT "CK_SMY_REG_ALIM_PORC" CHECK (PORCENTAJE_INGESTA BETWEEN 0 AND 100) ENABLE, 
	 CONSTRAINT "CK_SMY_REG_ALIM_ASIST" CHECK (ASISTIO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "PK_SMY_REGISTROS_ALIMENTACION" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_REG_ALIM_SLOT" UNIQUE ("ID_RESIDENTE", "FECHA", "ID_TIEMPO_COMIDA")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_REG_ALIM_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_REG_ALIM_RESID" FOREIGN KEY ("ID_RESIDENTE")
	  REFERENCES "SMY_RESIDENTES" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_REG_ALIM_TIEMPO" FOREIGN KEY ("ID_TIEMPO_COMIDA")
	  REFERENCES "SMY_TIEMPOS_COMIDA" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_REG_ALIM_PLAN" FOREIGN KEY ("ID_PLAN_NUTRICIONAL")
	  REFERENCES "SMY_PLAN_NUTRICIONAL" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_REG_ALIM_EMP" FOREIGN KEY ("ID_EMPLEADO_REGISTRA")
	  REFERENCES "SMY_EMPLEADOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
