CREATE TABLE SMY_TAREA_RESIDENTES 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_TAREA_OPERATIVA" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_RESIDENTE" NUMBER(10,0) NOT NULL ENABLE, 
	"ASISTIO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"OBSERVACIONES" VARCHAR2(255) COLLATE "USING_NLS_COMP", 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_TR_ASISTIO" CHECK (ASISTIO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "PK_SMY_TAREA_RES" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_TAREA_RES" UNIQUE ("ID_TAREA_OPERATIVA", "ID_RESIDENTE")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_TR_TAREA" FOREIGN KEY ("ID_TAREA_OPERATIVA")
	  REFERENCES "SMY_TAREAS_OPERATIVAS" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_TR_RESIDENTE" FOREIGN KEY ("ID_RESIDENTE")
	  REFERENCES "SMY_RESIDENTES" ("ID") ON DELETE CASCADE ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_TAREA_RESIDENTES IS 'Control nominal de asistencia, participación y excepciones de residentes en tareas asistenciales y terapéuticas grupales.';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.ASISTIO IS 'Indicador de asistencia o cumplimiento individual del residente (''S''/''N'').';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.FECHA_CREACION IS 'Fecha y hora de registro en base de datos con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.ID IS 'Identificador único y clave primaria de la tabla SMY_TAREA_RESIDENTES.';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.ID_RESIDENTE IS 'Clave foránea hacia SMY_RESIDENTES(ID) convocado a la actividad.';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.ID_TAREA_OPERATIVA IS 'Clave foránea hacia SMY_TAREAS_OPERATIVAS(ID) grupal.';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación del registro.';
COMMENT ON COLUMN SMY_TAREA_RESIDENTES.OBSERVACIONES IS 'Observaciones individuales o motivo de inasistencia/excepción.';
