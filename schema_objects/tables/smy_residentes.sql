CREATE TABLE SMY_RESIDENTES 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER(10,0), 
	"CODIGO_EXPEDIENTE" VARCHAR2(30) COLLATE "USING_NLS_COMP", 
	"ID_TIPO_IDENTIFICACION" NUMBER(10,0) NOT NULL ENABLE, 
	"IDENTIFICACION" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NOMBRES" VARCHAR2(80) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"APELLIDOS" VARCHAR2(80) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"FECHA_NACIMIENTO" DATE NOT NULL ENABLE, 
	"ID_GENERO" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ARCHIVO_FOTO_PERFIL" NUMBER(10,0), 
	"HABITACION" VARCHAR2(20) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"CAMA" VARCHAR2(10) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"EPS" VARCHAR2(80) COLLATE "USING_NLS_COMP", 
	"PLAN_COMPLEMENTARIO" VARCHAR2(80) COLLATE "USING_NLS_COMP", 
	"TIPO_SANGRE" VARCHAR2(5) COLLATE "USING_NLS_COMP", 
	"ID_NIVEL_MOVILIDAD" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_TIPO_DIETA" NUMBER(10,0) NOT NULL ENABLE, 
	"ALERTAS_CLINICAS" VARCHAR2(500) COLLATE "USING_NLS_COMP", 
	"ID_ESTADO_RESIDENTE" NUMBER(10,0) NOT NULL ENABLE, 
	"CODIGO_QR_TOKEN" VARCHAR2(64) COLLATE "USING_NLS_COMP", 
	"FECHA_INGRESO" DATE NOT NULL ENABLE, 
	"FECHA_EGRESO" DATE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	"LUGAR_NACIMIENTO" VARCHAR2(100) COLLATE "USING_NLS_COMP", 
	"ID_ESTADO_CIVIL" NUMBER(10,0), 
	"OCUPACION_HISTORICA" VARCHAR2(150) COLLATE "USING_NLS_COMP", 
	"NIVEL_EDUCATIVO" VARCHAR2(80) COLLATE "USING_NLS_COMP", 
	"RELIGION_CREENCIA" VARCHAR2(80) COLLATE "USING_NLS_COMP", 
	 CONSTRAINT "PK_SMY_RESIDENTES" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_RES_IDENT" UNIQUE ("ID_TIPO_IDENTIFICACION", "IDENTIFICACION")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_RES_QR" UNIQUE ("CODIGO_QR_TOKEN")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_RES_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_TIPO_IDENT" FOREIGN KEY ("ID_TIPO_IDENTIFICACION")
	  REFERENCES "SMY_TIPOS_IDENTIFICACION" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_GENERO" FOREIGN KEY ("ID_GENERO")
	  REFERENCES "SMY_GENEROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_MOVILIDAD" FOREIGN KEY ("ID_NIVEL_MOVILIDAD")
	  REFERENCES "SMY_NIVELES_MOVILIDAD" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_DIETA" FOREIGN KEY ("ID_TIPO_DIETA")
	  REFERENCES "SMY_TIPOS_DIETAS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_ESTADO" FOREIGN KEY ("ID_ESTADO_RESIDENTE")
	  REFERENCES "SMY_ESTADOS_RESIDENTES" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_ARC" FOREIGN KEY ("ID_ARCHIVO_FOTO_PERFIL")
	  REFERENCES "SMY_ARCHIVOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_RES_EST_CIVIL" FOREIGN KEY ("ID_ESTADO_CIVIL")
	  REFERENCES "SMY_ESTADOS_CIVILES" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_RESIDENTES IS 'Ficha integral maestra del residente, antecedentes demográficos, clínicos, ubicación y contacto.';
COMMENT ON COLUMN SMY_RESIDENTES.ALERTAS_CLINICAS IS 'Resumen de alergias, riesgos de caída o alertas asistenciales de alta visibilidad.';
COMMENT ON COLUMN SMY_RESIDENTES.APELLIDOS IS 'Apellidos del residente.';
COMMENT ON COLUMN SMY_RESIDENTES.CAMA IS 'Identificador de cama o puesto dentro de la habitación (A, B, etc.).';
COMMENT ON COLUMN SMY_RESIDENTES.CODIGO_EXPEDIENTE IS 'Código único de expediente o historia institucional del residente (ej. RES-2024-001).';
COMMENT ON COLUMN SMY_RESIDENTES.CODIGO_QR_TOKEN IS 'UUID o token criptográfico único para generación y escaneo seguro de códigos QR de cama/habitación.';
COMMENT ON COLUMN SMY_RESIDENTES.EPS IS 'Entidad Promotora de Salud (EPS) a la que está afiliado el residente.';
COMMENT ON COLUMN SMY_RESIDENTES.FECHA_CREACION IS 'Fecha y hora de registro en base de datos con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_RESIDENTES.FECHA_EGRESO IS 'Fecha de egreso o retiro formal de la institución.';
COMMENT ON COLUMN SMY_RESIDENTES.FECHA_INGRESO IS 'Fecha formal de ingreso y admisión al centro geriátrico.';
COMMENT ON COLUMN SMY_RESIDENTES.FECHA_NACIMIENTO IS 'Fecha de nacimiento del residente.';
COMMENT ON COLUMN SMY_RESIDENTES.HABITACION IS 'Número o denominación de la habitación asignada.';
COMMENT ON COLUMN SMY_RESIDENTES.ID IS 'Identificador único y clave primaria de la tabla SMY_RESIDENTES.';
COMMENT ON COLUMN SMY_RESIDENTES.IDENTIFICACION IS 'Número de documento o cédula de identificación del residente.';
COMMENT ON COLUMN SMY_RESIDENTES.ID_ARCHIVO_FOTO_PERFIL IS 'Identificador del archivo en SMY_ARCHIVOS con la fotografía oficial del residente.';
COMMENT ON COLUMN SMY_RESIDENTES.ID_CENTRO IS 'Clave foránea hacia SMY_CENTROS(ID) con la sede física en la que reside el adulto mayor.';
COMMENT ON COLUMN SMY_RESIDENTES.ID_ESTADO_CIVIL IS 'Clave foránea hacia SMY_ESTADOS_CIVILES.';
COMMENT ON COLUMN SMY_RESIDENTES.ID_ESTADO_RESIDENTE IS 'Clave foránea hacia SMY_ESTADOS_RESIDENTES(ID) (Activo, Hospitalizado, etc.).';
COMMENT ON COLUMN SMY_RESIDENTES.ID_GENERO IS 'Clave foránea hacia SMY_GENEROS(ID).';
COMMENT ON COLUMN SMY_RESIDENTES.ID_NIVEL_MOVILIDAD IS 'Clave foránea hacia SMY_NIVELES_MOVILIDAD(ID).';
COMMENT ON COLUMN SMY_RESIDENTES.ID_TIPO_DIETA IS 'Clave foránea hacia SMY_TIPOS_DIETAS(ID).';
COMMENT ON COLUMN SMY_RESIDENTES.ID_TIPO_IDENTIFICACION IS 'Clave foránea hacia SMY_TIPOS_IDENTIFICACION(ID) del residente.';
COMMENT ON COLUMN SMY_RESIDENTES.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación del registro.';
COMMENT ON COLUMN SMY_RESIDENTES.LUGAR_NACIMIENTO IS 'Municipio y departamento o país de nacimiento del adulto mayor.';
COMMENT ON COLUMN SMY_RESIDENTES.NIVEL_EDUCATIVO IS 'Nivel de escolaridad alcanzado (Primaria, Secundaria, Técnico, Universitario, etc.).';
COMMENT ON COLUMN SMY_RESIDENTES.NOMBRES IS 'Nombres del residente.';
COMMENT ON COLUMN SMY_RESIDENTES.OCUPACION_HISTORICA IS 'Oficio, profesión o actividad laboral que desempeñó durante su vida.';
COMMENT ON COLUMN SMY_RESIDENTES.PLAN_COMPLEMENTARIO IS 'Plan de medicina prepagada o póliza de salud complementaria.';
COMMENT ON COLUMN SMY_RESIDENTES.RELIGION_CREENCIA IS 'Creencia religiosa o espiritual del adulto mayor.';
COMMENT ON COLUMN SMY_RESIDENTES.TIPO_SANGRE IS 'Grupo sanguíneo y factor RH (ej. O+, A+, AB-).';
