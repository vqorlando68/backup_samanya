CREATE TABLE SMY_TRASLADOS_SEDES_DETALLE 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_TRASLADO" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ARTICULO" NUMBER(10,0) NOT NULL ENABLE, 
	"NUMERO_LOTE" VARCHAR2(50) COLLATE "USING_NLS_COMP", 
	"FECHA_VENCIMIENTO" DATE, 
	"CANTIDAD_ENVIADA" NUMBER(12,2) NOT NULL ENABLE, 
	"CANTIDAD_RECIBIDA" NUMBER(12,2), 
	"ESTADO_ITEM" VARCHAR2(30) COLLATE "USING_NLS_COMP" DEFAULT 'EN_TRANSITO' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	 CONSTRAINT "CK_SMY_TRSDET_CANT" CHECK (CANTIDAD_ENVIADA > 0) ENABLE, 
	 CONSTRAINT "PK_SMY_TRS_DET" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_TRSDET_TRS" FOREIGN KEY ("ID_TRASLADO")
	  REFERENCES "SMY_TRASLADOS_SEDES" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_TRSDET_ART" FOREIGN KEY ("ID_ARTICULO")
	  REFERENCES "SMY_ARTICULOS_CATALOGO" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
