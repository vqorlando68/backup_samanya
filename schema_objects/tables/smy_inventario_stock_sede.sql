CREATE TABLE SMY_INVENTARIO_STOCK_SEDE 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_BODEGA" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ARTICULO" NUMBER(10,0) NOT NULL ENABLE, 
	"NUMERO_LOTE" VARCHAR2(50) COLLATE "USING_NLS_COMP", 
	"FECHA_VENCIMIENTO" DATE, 
	"CANTIDAD_DISPONIBLE" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"CANTIDAD_RESERVADA" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"STOCK_MINIMO" NUMBER(10,2) DEFAULT 5 NOT NULL ENABLE, 
	"STOCK_MAXIMO" NUMBER(10,2) DEFAULT 50 NOT NULL ENABLE, 
	"PUNTO_REORDEN" NUMBER(10,2) DEFAULT 10, 
	"UBICACION_ESTANTE" VARCHAR2(60) COLLATE "USING_NLS_COMP", 
	"FECHA_ULTIMO_MOVIMIENTO" DATE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_STK_DISP" CHECK (CANTIDAD_DISPONIBLE >= 0) ENABLE, 
	 CONSTRAINT "CK_SMY_STK_RES" CHECK (CANTIDAD_RESERVADA >= 0) ENABLE, 
	 CONSTRAINT "PK_SMY_INV_STOCK" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_STK_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_STK_BODEGA" FOREIGN KEY ("ID_BODEGA")
	  REFERENCES "SMY_BODEGAS_SEDE" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_STK_ARTICULO" FOREIGN KEY ("ID_ARTICULO")
	  REFERENCES "SMY_ARTICULOS_CATALOGO" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_INVENTARIO_STOCK_SEDE IS 'Control de existencias físicas, lotes, fechas de vencimiento y niveles de stock por bodega en cada sede.';
COMMENT ON COLUMN SMY_INVENTARIO_STOCK_SEDE.CANTIDAD_DISPONIBLE IS 'Existencia real en físico disponible para consumo o entrega.';
COMMENT ON COLUMN SMY_INVENTARIO_STOCK_SEDE.PUNTO_REORDEN IS 'Nivel de alerta amarilla preventiva para realizar pedido de compra.';
COMMENT ON COLUMN SMY_INVENTARIO_STOCK_SEDE.STOCK_MINIMO IS 'Nivel mínimo tolerable antes de disparar alerta roja de desabastecimiento.';
