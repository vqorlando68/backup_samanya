CREATE TABLE SMY_BODEGAS_SEDE 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER(10,0) NOT NULL ENABLE, 
	"CODIGO_BODEGA" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NOMBRE_BODEGA" VARCHAR2(80) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DESCRIPCION" VARCHAR2(200) COLLATE "USING_NLS_COMP", 
	"ES_BODEGA_PRINCIPAL" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"ESTADO" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'Activo' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_BOD_PRIN" CHECK (ES_BODEGA_PRINCIPAL IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_BOD_ESTADO" CHECK (ESTADO IN ('Activo', 'Inactivo')) ENABLE, 
	 CONSTRAINT "PK_SMY_BODEGAS_SEDE" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_BOD_CEN_COD" UNIQUE ("ID_CENTRO", "CODIGO_BODEGA")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_BOD_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_BODEGAS_SEDE IS 'Almacenes, bodegas y farmacias físicas pertenecientes a cada sede asistencial.';
COMMENT ON COLUMN SMY_BODEGAS_SEDE.CODIGO_BODEGA IS 'Código de la bodega dentro de la sede (ej. BOD-PRIN, FARM-SEDE, ALAC-COCINA).';
COMMENT ON COLUMN SMY_BODEGAS_SEDE.ES_BODEGA_PRINCIPAL IS 'Indica si es el almacén receptor principal por defecto de la sede (S/N).';
COMMENT ON COLUMN SMY_BODEGAS_SEDE.ID_CENTRO IS 'Clave foránea hacia SMY_CENTROS(ID).';
