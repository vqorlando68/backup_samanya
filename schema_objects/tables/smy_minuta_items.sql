CREATE TABLE SMY_MINUTA_ITEMS 
   (	"ID" NUMBER NOT NULL ENABLE, 
	"ID_MINUTA" NUMBER NOT NULL ENABLE, 
	"DIA_SEMANA" NUMBER NOT NULL ENABLE, 
	"ID_TIEMPO_COMIDA" NUMBER NOT NULL ENABLE, 
	"PLATO_PRINCIPAL" VARCHAR2(300) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"ACOMPANAMIENTO" VARCHAR2(300) COLLATE "USING_NLS_COMP", 
	"BEBIDA" VARCHAR2(200) COLLATE "USING_NLS_COMP", 
	"POSTRE" VARCHAR2(200) COLLATE "USING_NLS_COMP", 
	"CALORIAS_ESTIMADAS" NUMBER, 
	"OBSERVACIONES_DIETAS" VARCHAR2(500) COLLATE "USING_NLS_COMP", 
	"CREADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP" DEFAULT 'SISTEMA' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ACTUALIZADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP", 
	"FECHA_ACTUALIZACION" DATE, 
	 CONSTRAINT "CK_SMY_MIN_IT_DIA" CHECK (DIA_SEMANA BETWEEN 1 AND 7) ENABLE, 
	 CONSTRAINT "PK_SMY_MINUTA_ITEMS" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_MIN_ITEM_SLOT" UNIQUE ("ID_MINUTA", "DIA_SEMANA", "ID_TIEMPO_COMIDA")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_MIN_IT_MINUTA" FOREIGN KEY ("ID_MINUTA")
	  REFERENCES "SMY_MINUTAS_SEMANALES" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_MIN_IT_TIEMPO" FOREIGN KEY ("ID_TIEMPO_COMIDA")
	  REFERENCES "SMY_TIEMPOS_COMIDA" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
