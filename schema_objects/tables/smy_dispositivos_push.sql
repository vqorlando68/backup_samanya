CREATE TABLE SMY_DISPOSITIVOS_PUSH 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE, 
	"TOKEN_DISPOSITIVO" VARCHAR2(500) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"PLATAFORMA" VARCHAR2(20) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"FECHA_ULTIMO_USO" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ACTIVO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_DP_ACTIVO" CHECK (ACTIVO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_DP_PLATAFORMA" CHECK (PLATAFORMA IN ('ANDROID', 'IOS', 'WEB')) ENABLE, 
	 CONSTRAINT "PK_SMY_DISP_PUSH" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_DP_TOKEN" UNIQUE ("TOKEN_DISPOSITIVO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_DP_USUARIO" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "SMY_USUARIOS" ("ID") ON DELETE CASCADE ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_DISPOSITIVOS_PUSH IS 'Registro de tokens de dispositivos móviles (FCM/APNs) para envío de notificaciones push a cuidadores y familiares.';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.ACTIVO IS 'Indicador de estado activo del token para envíos (''S''/''N'').';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.FECHA_CREACION IS 'Fecha y hora de registro en base de datos con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.FECHA_ULTIMO_USO IS 'Fecha del último despacho o apertura de notificación en el dispositivo.';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.ID IS 'Identificador único y clave primaria de la tabla SMY_DISPOSITIVOS_PUSH.';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.ID_USUARIO IS 'Clave foránea hacia SMY_USUARIOS(ID) titular del dispositivo móvil.';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación del registro.';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.PLATAFORMA IS 'Sistema operativo del dispositivo móvil (ANDROID, IOS, WEB).';
COMMENT ON COLUMN SMY_DISPOSITIVOS_PUSH.TOKEN_DISPOSITIVO IS 'Token push criptográfico generado por Firebase Cloud Messaging o Apple APNs.';
