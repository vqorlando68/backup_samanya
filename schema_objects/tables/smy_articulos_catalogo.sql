CREATE TABLE SMY_ARTICULOS_CATALOGO 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ORGANIZACION" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CATEGORIA" NUMBER(10,0) NOT NULL ENABLE, 
	"CODIGO_ARTICULO" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NOMBRE_ARTICULO" VARCHAR2(120) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DESCRIPCION" VARCHAR2(300) COLLATE "USING_NLS_COMP", 
	"UNIDAD_MEDIDA" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'UNIDAD' NOT NULL ENABLE, 
	"REQUIERE_LOTE_VENCIMIENTO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"ES_DESCONTABLE_POR_RESIDENTE" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"COSTO_ESTANDAR" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"ESTADO" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'Activo' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_ART_CAT_LOTE" CHECK (REQUIERE_LOTE_VENCIMIENTO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_ART_CAT_DESC" CHECK (ES_DESCONTABLE_POR_RESIDENTE IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_ART_CAT_EST" CHECK (ESTADO IN ('Activo', 'Inactivo')) ENABLE, 
	 CONSTRAINT "PK_SMY_ART_CATALOGO" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_ART_CAT_COD" UNIQUE ("ID_ORGANIZACION", "CODIGO_ARTICULO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_ART_CAT_ORG" FOREIGN KEY ("ID_ORGANIZACION")
	  REFERENCES "SMY_ORGANIZACIONES" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_ART_CAT_CAT" FOREIGN KEY ("ID_CATEGORIA")
	  REFERENCES "SMY_CATEGORIAS_ARTICULOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_ARTICULOS_CATALOGO IS 'Maestro de artículos, insumos, medicamentos de stock, dotación y suministros de la organización.';
COMMENT ON COLUMN SMY_ARTICULOS_CATALOGO.CODIGO_ARTICULO IS 'Código único de inventario del producto (ej. INS-GLUC-01, ASEO-JAB-02).';
COMMENT ON COLUMN SMY_ARTICULOS_CATALOGO.ES_DESCONTABLE_POR_RESIDENTE IS 'Indica si este artículo puede ser cargado o asignado al consumo de un residente (S/N).';
COMMENT ON COLUMN SMY_ARTICULOS_CATALOGO.REQUIERE_LOTE_VENCIMIENTO IS 'Indica si exige registrar número de lote y fecha de vencimiento (S/N).';
COMMENT ON COLUMN SMY_ARTICULOS_CATALOGO.UNIDAD_MEDIDA IS 'Unidad de manejo: UNIDAD, CAJA, PAQUETE, FRASCO, LITRO, KILO, ROLLO.';
