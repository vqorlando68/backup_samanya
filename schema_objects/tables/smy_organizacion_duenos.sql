CREATE TABLE SMY_ORGANIZACION_DUENOS 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ORGANIZACION" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE, 
	"PORCENTAJE_PARTICIPACION" NUMBER(5,2) DEFAULT 100.00, 
	"ES_REPRESENTANTE_LEGAL" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"FECHA_VINCULACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"FECHA_RETIRO" DATE, 
	"ESTADO_ACTIVO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_ORG_DUE_REP" CHECK (ES_REPRESENTANTE_LEGAL IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_ORG_DUE_ACT" CHECK (ESTADO_ACTIVO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "PK_SMY_ORG_DUENOS" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_ORG_DUE" UNIQUE ("ID_ORGANIZACION", "ID_USUARIO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_ORG_DUE_ORG" FOREIGN KEY ("ID_ORGANIZACION")
	  REFERENCES "SMY_ORGANIZACIONES" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_ORG_DUE_USR" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "SMY_USUARIOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_ORGANIZACION_DUENOS IS 'Registro de personas propietarias/socias con titularidad sobre organizaciones y franquicias geriátricas.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.ESTADO_ACTIVO IS 'Indicador booleano (S/N) de vinculación activa.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.ES_REPRESENTANTE_LEGAL IS 'Indicador booleano (S/N) si el usuario es representante legal.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.FECHA_CREACION IS 'Fecha y hora de registro con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.FECHA_RETIRO IS 'Fecha de cesión o retiro de la participación societaria.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.FECHA_VINCULACION IS 'Fecha en que adquiere la condición de dueño o socio.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.ID IS 'Identificador único y clave primaria de la tabla SMY_ORGANIZACION_DUENOS.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.ID_ORGANIZACION IS 'Clave foránea hacia SMY_ORGANIZACIONES(ID).';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.ID_USUARIO IS 'Clave foránea hacia SMY_USUARIOS(ID) del propietario.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación.';
COMMENT ON COLUMN SMY_ORGANIZACION_DUENOS.PORCENTAJE_PARTICIPACION IS 'Porcentaje de participación patrimonial o societaria en la organización.';
