CREATE TABLE SMY_RESIDENTE_ACUDIENTE 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_RESIDENTE" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ACUDIENTE" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_PARENTESCO" NUMBER(10,0) NOT NULL ENABLE, 
	"ES_PRINCIPAL" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"ES_RESPONSABLE_PAGO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"AUTORIZADO_SALIDAS" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	"ES_CERCANIA_AFECTIVA" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"ASUME_ACOMPANAMIENTO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"FRECUENCIA_CONTACTO" VARCHAR2(40) COLLATE "USING_NLS_COMP", 
	"AUTORIZADO_INFO_MEDICA" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"AUTORIZADO_ACOMPANAR_CITAS" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"AUTORIZADO_TRAMITES" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"RELACION_NOTAS" VARCHAR2(500) COLLATE "USING_NLS_COMP", 
	 CONSTRAINT "CK_SMY_RA_PRINCIPAL" CHECK (ES_PRINCIPAL IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_RA_PAGO" CHECK (ES_RESPONSABLE_PAGO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_RA_SALIDAS" CHECK (AUTORIZADO_SALIDAS IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "PK_SMY_RES_ACU" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_RES_ACU" UNIQUE ("ID_RESIDENTE", "ID_ACUDIENTE")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CK_SMY_RESACU_CERCA" CHECK (ES_CERCANIA_AFECTIVA IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_RESACU_ACOMP" CHECK (ASUME_ACOMPANAMIENTO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_RESACU_INFOMED" CHECK (AUTORIZADO_INFO_MEDICA IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_RESACU_ACITAS" CHECK (AUTORIZADO_ACOMPANAR_CITAS IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_RESACU_TRAM" CHECK (AUTORIZADO_TRAMITES IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "FK_SMY_RA_RESIDENTE" FOREIGN KEY ("ID_RESIDENTE")
	  REFERENCES "SMY_RESIDENTES" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_RA_ACUDIENTE" FOREIGN KEY ("ID_ACUDIENTE")
	  REFERENCES "SMY_ACUDIENTES" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_RA_PARENTESCO" FOREIGN KEY ("ID_PARENTESCO")
	  REFERENCES "SMY_PARENTESCOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_RESIDENTE_ACUDIENTE IS 'Tabla de relación asociativa multidireccional entre residentes y sus acudientes o tutores.';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ASUME_ACOMPANAMIENTO IS 'Indica si es la persona que asume principalmente el acompañamiento (S/N).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.AUTORIZADO_ACOMPANAR_CITAS IS 'Autorizado para acompañar al residente a citas médicas externas (S/N).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.AUTORIZADO_INFO_MEDICA IS 'Autorizado formalmente para recibir información médica confidencial (S/N).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.AUTORIZADO_SALIDAS IS 'Indicador de autorización expresa para retirar al residente del centro (''S''/''N'').';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.AUTORIZADO_TRAMITES IS 'Autorizado para realizar diligencias y trámites institucionales (S/N).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ES_CERCANIA_AFECTIVA IS 'Indica si es la persona de mayor cercanía afectiva identificada (S/N).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ES_PRINCIPAL IS 'Indicador de contacto de emergencia prioritario (''S''/''N'').';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ES_RESPONSABLE_PAGO IS 'Indicador de responsabilidad legal y económica de pagos (''S''/''N'').';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.FECHA_CREACION IS 'Fecha y hora de registro en base de datos con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.FRECUENCIA_CONTACTO IS 'Frecuencia esperada de contacto/visita (DIARIO, SEMANAL, QUINCENAL, MENSUAL, ESPORADICO).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ID IS 'Identificador único y clave primaria de la tabla SMY_RESIDENTE_ACUDIENTE.';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ID_ACUDIENTE IS 'Clave foránea hacia SMY_ACUDIENTES(ID).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ID_PARENTESCO IS 'Clave foránea hacia SMY_PARENTESCOS(ID) que define el vínculo familiar.';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ID_RESIDENTE IS 'Clave foránea hacia SMY_RESIDENTES(ID).';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación del registro.';
COMMENT ON COLUMN SMY_RESIDENTE_ACUDIENTE.RELACION_NOTAS IS 'Observaciones sobre la relación o dinámicas familiares relevantes.';
