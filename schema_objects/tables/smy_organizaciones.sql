CREATE TABLE SMY_ORGANIZACIONES 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"CODIGO_ORGANIZACION" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"RAZON_SOCIAL" VARCHAR2(150) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NOMBRE_COMERCIAL" VARCHAR2(120) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NUMERO_IDENTIFICACION_TRIB" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"ID_TIPO_IDENTIFICACION" NUMBER(10,0) NOT NULL ENABLE, 
	"EMAIL_CORPORATIVO" VARCHAR2(120) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"TELEFONO_CONTACTO" VARCHAR2(30) COLLATE "USING_NLS_COMP", 
	"SITIO_WEB" VARCHAR2(200) COLLATE "USING_NLS_COMP", 
	"ID_ARCHIVO_LOGO" NUMBER(10,0), 
	"ID_ESTADO_ORGANIZACION" NUMBER(10,0) DEFAULT 1 NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	"MANEJA_INVENTARIO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"MANEJA_COSTOS_INVENTARIO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"MANEJA_ALIMENTACION" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	 CONSTRAINT "PK_SMY_ORGANIZACIONES" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_ORG_COD" UNIQUE ("CODIGO_ORGANIZACION")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_ORG_NIT" UNIQUE ("NUMERO_IDENTIFICACION_TRIB")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CK_SMY_ORG_MAN_INV" CHECK (MANEJA_INVENTARIO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_ORG_MAN_COST" CHECK (MANEJA_COSTOS_INVENTARIO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_ORG_MAN_ALIM" CHECK (MANEJA_ALIMENTACION IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "FK_SMY_ORG_ESTADO" FOREIGN KEY ("ID_ESTADO_ORGANIZACION")
	  REFERENCES "SMY_ESTADOS_ORGANIZACIONES" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_ORG_ARC" FOREIGN KEY ("ID_ARCHIVO_LOGO")
	  REFERENCES "SMY_ARCHIVOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_ORGANIZACIONES IS 'Entidad raíz de negocio para arquitectura multi-tenancy: agrupa múltiples sedes y centros geriátricos bajo una misma personería jurídica o franquicia.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.CODIGO_ORGANIZACION IS 'Código de negocio único de la organización o tenant (ej. ORG-BIENESTAR).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.EMAIL_CORPORATIVO IS 'Correo electrónico corporativo principal de contacto.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.FECHA_CREACION IS 'Fecha y hora de registro con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.ID IS 'Identificador único y clave primaria de la tabla SMY_ORGANIZACIONES.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.ID_ARCHIVO_LOGO IS 'Identificador en SMY_ARCHIVOS del logotipo corporativo oficial de la organización.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.ID_ESTADO_ORGANIZACION IS 'Clave foránea hacia SMY_ESTADOS_ORGANIZACIONES(ID).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.ID_TIPO_IDENTIFICACION IS 'Clave foránea hacia SMY_TIPOS_IDENTIFICACION(ID) del documento fiscal.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.MANEJA_ALIMENTACION IS 'Flag maestro: Determina si la organización tiene habilitado el módulo de alimentación y nutrición (S/N).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.MANEJA_COSTOS_INVENTARIO IS 'Flag maestro: Indica si la organización maneja costos/precios en inventario (S) o solo control de cantidades físicas (N).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.MANEJA_INVENTARIO IS 'Flag maestro: Indica si la organización tiene contratado/habilitado el módulo de inventarios (S/N).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.NOMBRE_COMERCIAL IS 'Nombre de marca comercial de la institución geriátrica.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.NUMERO_IDENTIFICACION_TRIB IS 'Número de identificación tributaria (NIT, CIF o RUT).';
COMMENT ON COLUMN SMY_ORGANIZACIONES.RAZON_SOCIAL IS 'Razón social legalmente registrada ante entidades tributarias.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.SITIO_WEB IS 'Dirección web o portal institucional.';
COMMENT ON COLUMN SMY_ORGANIZACIONES.TELEFONO_CONTACTO IS 'Número telefónico corporativo de la organización.';
