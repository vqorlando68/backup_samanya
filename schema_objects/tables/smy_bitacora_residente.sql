CREATE TABLE SMY_BITACORA_RESIDENTE 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_RESIDENTE" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_EMPLEADO" NUMBER(10,0), 
	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE, 
	"FECHA" DATE NOT NULL ENABLE, 
	"HORA" VARCHAR2(8) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"ID_CATEGORIA_BITACORA" NUMBER(10,0) NOT NULL ENABLE, 
	"CONTENIDO" CLOB COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"GRABADO_POR_VOZ" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"ID_ARCHIVO_AUDIO" NUMBER(10,0), 
	"ID_ARCHIVO_FOTO" NUMBER(10,0), 
	"ID_TURNO_ASIGNADO" NUMBER(10,0), 
	"VISIBLE_ACUDIENTE" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_BIT_VOZ" CHECK (GRABADO_POR_VOZ IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_BIT_VIS_ACU" CHECK (VISIBLE_ACUDIENTE IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "PK_SMY_BIT_RESIDENTE" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_RESIDENTE" FOREIGN KEY ("ID_RESIDENTE")
	  REFERENCES "SMY_RESIDENTES" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_EMPLEADO" FOREIGN KEY ("ID_EMPLEADO")
	  REFERENCES "SMY_EMPLEADOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_USUARIO" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "SMY_USUARIOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_TURNO" FOREIGN KEY ("ID_TURNO_ASIGNADO")
	  REFERENCES "SMY_TURNOS_ASIGNADOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_CATEGORIA" FOREIGN KEY ("ID_CATEGORIA_BITACORA")
	  REFERENCES "SMY_CATEGORIAS_BITACORA" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_ARC_AUD" FOREIGN KEY ("ID_ARCHIVO_AUDIO")
	  REFERENCES "SMY_ARCHIVOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_BIT_ARC_FOT" FOREIGN KEY ("ID_ARCHIVO_FOTO")
	  REFERENCES "SMY_ARCHIVOS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_BITACORA_RESIDENTE IS 'Registro cronológico continuo de novedades asistenciales, estado de ánimo y observaciones diarias.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.CONTENIDO IS 'Campo de datos para contenido en SMY_BITACORA_RESIDENTE.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.FECHA IS 'Fecha calendario correspondiente a la novedad asistencial.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.FECHA_CREACION IS 'Fecha y hora de registro en base de datos con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.GRABADO_POR_VOZ IS 'Campo de datos para grabado por voz en SMY_BITACORA_RESIDENTE.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.HORA IS 'Hora del suceso en formato HH24:MI (ej. 10:30).';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID IS 'Identificador único y clave primaria de la tabla SMY_BITACORA_RESIDENTE.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_ARCHIVO_AUDIO IS 'Clave foránea hacia SMY_ARCHIVOS(ID) de la nota de voz o audio dictado.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_ARCHIVO_FOTO IS 'Clave foránea hacia SMY_ARCHIVOS(ID) de la fotografía adjunta a la anotación.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_CATEGORIA_BITACORA IS 'Clave foránea hacia SMY_CATEGORIAS_BITACORA(ID).';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_EMPLEADO IS 'Clave foránea que referencia al registro correspondiente a: empleado.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_RESIDENTE IS 'Clave foránea hacia SMY_RESIDENTES(ID) sobre el que se hace la anotación.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_TURNO_ASIGNADO IS 'Clave foránea que referencia al registro correspondiente a: turno asignado.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_USUARIO IS 'Clave foránea que referencia al registro correspondiente a: usuario.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación del registro.';
COMMENT ON COLUMN SMY_BITACORA_RESIDENTE.VISIBLE_ACUDIENTE IS 'Campo de datos para visible acudiente en SMY_BITACORA_RESIDENTE.';
