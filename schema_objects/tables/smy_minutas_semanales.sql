CREATE TABLE SMY_MINUTAS_SEMANALES 
   (	"ID" NUMBER NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER NOT NULL ENABLE, 
	"NOMBRE" VARCHAR2(150) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DESCRIPCION" VARCHAR2(500) COLLATE "USING_NLS_COMP", 
	"FECHA_INICIO" DATE NOT NULL ENABLE, 
	"FECHA_FIN" DATE NOT NULL ENABLE, 
	"ESTADO" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'ACTIVO' NOT NULL ENABLE, 
	"CREADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP" DEFAULT 'SISTEMA' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ACTUALIZADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP", 
	"FECHA_ACTUALIZACION" DATE, 
	 CONSTRAINT "CK_SMY_MINUTAS_EST" CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')) ENABLE, 
	 CONSTRAINT "PK_SMY_MINUTAS_SEMANALES" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_MINUTAS_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
