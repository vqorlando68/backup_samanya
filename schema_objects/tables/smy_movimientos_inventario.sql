CREATE TABLE SMY_MOVIMIENTOS_INVENTARIO 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER(10,0) NOT NULL ENABLE, 
	"NUMERO_DOCUMENTO" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"TIPO_MOVIMIENTO" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"FECHA_MOVIMIENTO" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_REGISTRA" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_RESIDENTE" NUMBER(10,0), 
	"ID_PROVEEDOR" NUMBER(10,0), 
	"OBSERVACIONES" VARCHAR2(500) COLLATE "USING_NLS_COMP", 
	"ESTADO" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'APLICADO' NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_MOV_TIPO" CHECK (TIPO_MOVIMIENTO IN (
            'ENTRADA_COMPRA', 'ENTRADA_DONACION', 'SALIDA_CONSUMO_SEDE',
            'SALIDA_ENTREGA_RESIDENTE', 'SALIDA_MERMA_VENCIDO',
            'AJUSTE_FISICO_POSITIVO', 'AJUSTE_FISICO_NEGATIVO',
            'TRASLADO_SALIDA', 'TRASLADO_ENTRADA'
        )) ENABLE, 
	 CONSTRAINT "CK_SMY_MOV_EST" CHECK (ESTADO IN ('APLICADO', 'ANULADO')) ENABLE, 
	 CONSTRAINT "PK_SMY_MOV_INV" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_MOV_DOC" UNIQUE ("NUMERO_DOCUMENTO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_MOV_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_MOV_USUARIO" FOREIGN KEY ("ID_USUARIO_REGISTRA")
	  REFERENCES "SMY_USUARIOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_MOV_RESID" FOREIGN KEY ("ID_RESIDENTE")
	  REFERENCES "SMY_RESIDENTES" ("ID") ON DELETE SET NULL ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_MOVIMIENTOS_INVENTARIO IS 'Cabecera de movimientos de almacén, entradas, salidas asistenciales, traslados y ajustes de inventario.';
COMMENT ON COLUMN SMY_MOVIMIENTOS_INVENTARIO.ID_RESIDENTE IS 'Clave foránea hacia SMY_RESIDENTES(ID) si el insumo fue entregado o consumido por un residente.';
COMMENT ON COLUMN SMY_MOVIMIENTOS_INVENTARIO.NUMERO_DOCUMENTO IS 'Número oficial del comprobante (ej. INV-ENT-2026-0001, INV-SAL-2026-0042).';
