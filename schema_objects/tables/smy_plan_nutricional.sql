	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ACTUALIZADO_POR" VARCHAR2(100) COLLATE "USING_NLS_COMP", 
	"FECHA_ACTUALIZACION" DATE, 
	 CONSTRAINT "CK_SMY_PLAN_NUT_ASIST" CHECK (REQUIERE_ASISTENCIA IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_PLAN_NUT_EST" CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')) ENABLE, 
	 CONSTRAINT "PK_SMY_PLAN_NUT" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_PLAN_NUT_CENTRO" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_PLAN_NUT_RESID" FOREIGN KEY ("ID_RESIDENTE")
	  REFERENCES "SMY_RESIDENTES" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_PLAN_NUT_DIETA" FOREIGN KEY ("ID_TIPO_DIETA")
	  REFERENCES "SMY_TIPOS_DIETAS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_PLAN_NUT_CONS" FOREIGN KEY ("ID_CONSISTENCIA")
	  REFERENCES "SMY_CONSISTENCIAS_DIETA" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_PLAN_NUT_ESP" FOREIGN KEY ("ID_NIVEL_ESPESANTE")
	  REFERENCES "SMY_NIVELES_ESPESANTE" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;
