CREATE TABLE SMY_PLAN_NUTRICIONAL 
   (	"ID" NUMBER NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER NOT NULL ENABLE, 
	"ID_RESIDENTE" NUMBER NOT NULL ENABLE, 
	"ID_TIPO_DIETA" NUMBER, 
	"ID_CONSISTENCIA" NUMBER, 
	"ID_NIVEL_ESPESANTE" NUMBER, 
	"REQUERIMIENTO_CALORICO_KCAL" NUMBER, 
	"RESTRICCIONES_ALERGIAS" VARCHAR2(1000) COLLATE "USING_NLS_COMP", 
	"ALIMENTOS_PREFERIDOS" VARCHAR2(1000) COLLATE "USING_NLS_COMP", 
	"ALIMENTOS_RECHAZADOS" VARCHAR2(1000) COLLATE "USING_NLS_COMP", 
	"REQUIERE_ASISTENCIA" VARCHAR2(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"SUPLEMENTO_NUTRICIONAL" VARCHAR2(500) COLLATE "USING_NLS_COMP", 
	"OBSERVACIONES" VARCHAR2(2000) COLLATE "USING_NLS_COMP", 
	"ESTADO" VARCHAR2(20) COLLATE "USING_NLS_COMP" DEFAULT 'ACTIVO' NOT NULL ENABLE, 
