CREATE TABLE SMY_ESTADOS_ORGANIZACIONES 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"NOMBRE_ESTADO" VARCHAR2(50) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DESCRIPCION" VARCHAR2(200) COLLATE "USING_NLS_COMP", 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "PK_SMY_ESTADOS_ORG" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_EST_ORG_NOM" UNIQUE ("NOMBRE_ESTADO")
  USING INDEX  ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_ESTADOS_ORGANIZACIONES IS 'Catálogo maestro de estados operativos y contractuales para organizaciones geriátricas.';
COMMENT ON COLUMN SMY_ESTADOS_ORGANIZACIONES.DESCRIPCION IS 'Descripción del significado operativo del estado.';
COMMENT ON COLUMN SMY_ESTADOS_ORGANIZACIONES.FECHA_CREACION IS 'Fecha y hora de registro con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_ESTADOS_ORGANIZACIONES.ID IS 'Identificador único y clave primaria de la tabla SMY_ESTADOS_ORGANIZACIONES.';
COMMENT ON COLUMN SMY_ESTADOS_ORGANIZACIONES.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación.';
COMMENT ON COLUMN SMY_ESTADOS_ORGANIZACIONES.NOMBRE_ESTADO IS 'Nombre descriptivo único del estado de la organización.';
