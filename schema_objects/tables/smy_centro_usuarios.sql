CREATE TABLE SMY_CENTRO_USUARIOS 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_CENTRO" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_USUARIO" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ROL" NUMBER(10,0) NOT NULL ENABLE, 
	"ES_SEDE_PRINCIPAL" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'N' NOT NULL ENABLE, 
	"ESTADO_ACTIVO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"FECHA_ASIGNACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	 CONSTRAINT "CK_SMY_CEN_USR_PRI" CHECK (ES_SEDE_PRINCIPAL IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_CEN_USR_ACT" CHECK (ESTADO_ACTIVO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "PK_SMY_CENTRO_USUARIOS" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_CEN_USR" UNIQUE ("ID_CENTRO", "ID_USUARIO", "ID_ROL")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_CEN_USR_CEN" FOREIGN KEY ("ID_CENTRO")
	  REFERENCES "SMY_CENTROS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_CEN_USR_USR" FOREIGN KEY ("ID_USUARIO")
	  REFERENCES "SMY_USUARIOS" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_CEN_USR_ROL" FOREIGN KEY ("ID_ROL")
	  REFERENCES "SMY_ROLES" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_CENTRO_USUARIOS IS 'Asignación de usuarios a centros/sedes geriátricas con rol específico por sede. Permite a una persona administrar o laborar en múltiples centros.';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ESTADO_ACTIVO IS 'Indicador booleano (S/N) de vigencia de la asignación.';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ES_SEDE_PRINCIPAL IS 'Indicador booleano (S/N) de sede principal o preferente al iniciar sesión.';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.FECHA_ASIGNACION IS 'Fecha y hora en que se asigna la persona a la sede.';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.FECHA_CREACION IS 'Fecha y hora de registro con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ID IS 'Identificador único y clave primaria de la tabla SMY_CENTRO_USUARIOS.';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ID_CENTRO IS 'Clave foránea hacia SMY_CENTROS(ID) donde opera el usuario.';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ID_ROL IS 'Clave foránea hacia SMY_ROLES(ID) que ejerce en dicho centro (ej. ADMIN, CUIDADOR, MEDICO).';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ID_USUARIO IS 'Clave foránea hacia SMY_USUARIOS(ID).';
COMMENT ON COLUMN SMY_CENTRO_USUARIOS.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación.';
