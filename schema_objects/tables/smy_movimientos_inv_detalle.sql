CREATE TABLE SMY_MOVIMIENTOS_INV_DETALLE 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_MOVIMIENTO" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_BODEGA" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ARTICULO" NUMBER(10,0) NOT NULL ENABLE, 
	"NUMERO_LOTE" VARCHAR2(50) COLLATE "USING_NLS_COMP", 
	"FECHA_VENCIMIENTO" DATE, 
	"CANTIDAD" NUMBER(12,2) NOT NULL ENABLE, 
	"COSTO_UNITARIO" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"COSTO_TOTAL" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"SALDO_ANTERIOR" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"SALDO_POSTERIOR" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	 CONSTRAINT "CK_SMY_MOVDET_CANT" CHECK (CANTIDAD > 0) ENABLE, 
	 CONSTRAINT "PK_SMY_MOV_DET" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_SMY_MOVDET_MOV" FOREIGN KEY ("ID_MOVIMIENTO")
	  REFERENCES "SMY_MOVIMIENTOS_INVENTARIO" ("ID") ON DELETE CASCADE ENABLE, 
	 CONSTRAINT "FK_SMY_MOVDET_BOD" FOREIGN KEY ("ID_BODEGA")
	  REFERENCES "SMY_BODEGAS_SEDE" ("ID") ENABLE, 
	 CONSTRAINT "FK_SMY_MOVDET_ART" FOREIGN KEY ("ID_ARTICULO")
	  REFERENCES "SMY_ARTICULOS_CATALOGO" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_MOVIMIENTOS_INV_DETALLE IS 'Renglones y líneas de kardex detalladas con auditoría de saldos antes y después de la operación.';
COMMENT ON COLUMN SMY_MOVIMIENTOS_INV_DETALLE.SALDO_ANTERIOR IS 'Existencia de la bodega antes de aplicar la transacción.';
COMMENT ON COLUMN SMY_MOVIMIENTOS_INV_DETALLE.SALDO_POSTERIOR IS 'Existencia resultante en bodega tras aplicar la transacción.';
