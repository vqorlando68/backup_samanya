CREATE TABLE SMY_CENTROS 
   (	"ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ID_ORGANIZACION" NUMBER(10,0) NOT NULL ENABLE, 
	"CODIGO_CENTRO" VARCHAR2(30) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"NOMBRE_CENTRO" VARCHAR2(120) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"SLUG_DIRECTORIO" VARCHAR2(60) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"CIUDAD" VARCHAR2(80) COLLATE "USING_NLS_COMP" NOT NULL ENABLE, 
	"DIRECCION" VARCHAR2(200) COLLATE "USING_NLS_COMP", 
	"TELEFONO" VARCHAR2(30) COLLATE "USING_NLS_COMP", 
	"EMAIL_CONTACTO" VARCHAR2(100) COLLATE "USING_NLS_COMP", 
	"CAPACIDAD_RESIDENTES" NUMBER(5,0) DEFAULT 0 NOT NULL ENABLE, 
	"ID_ESTADO_CENTRO" NUMBER(10,0) DEFAULT 1 NOT NULL ENABLE, 
	"FECHA_CREACION" DATE DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL ENABLE, 
	"ID_USUARIO_ULTIMA_MODIFICACION" NUMBER(10,0), 
	"MANEJA_INVENTARIO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"MANEJA_COSTOS_INVENTARIO" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	"MANEJA_ALIMENTACION" CHAR(1) COLLATE "USING_NLS_COMP" DEFAULT 'S' NOT NULL ENABLE, 
	 CONSTRAINT "PK_SMY_CENTROS" PRIMARY KEY ("ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_CEN_COD" UNIQUE ("CODIGO_CENTRO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_SMY_CEN_SLUG" UNIQUE ("SLUG_DIRECTORIO")
  USING INDEX  ENABLE, 
	 CONSTRAINT "CK_SMY_CEN_MAN_INV" CHECK (MANEJA_INVENTARIO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_CEN_MAN_COST" CHECK (MANEJA_COSTOS_INVENTARIO IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "CK_SMY_CEN_MAN_ALIM" CHECK (MANEJA_ALIMENTACION IN ('S', 'N')) ENABLE, 
	 CONSTRAINT "FK_SMY_CEN_ORG" FOREIGN KEY ("ID_ORGANIZACION")
	  REFERENCES "SMY_ORGANIZACIONES" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;

COMMENT ON TABLE SMY_CENTROS IS 'Catálogo maestro de centros y sedes asistenciales físicas asociadas a una organización.';
COMMENT ON COLUMN SMY_CENTROS.CODIGO_CENTRO IS 'Código de negocio único de la sede (ej. SEDE-CENTRO).';
COMMENT ON COLUMN SMY_CENTROS.FECHA_CREACION IS 'Fecha y hora de registro con zona horaria legal de Bogotá (UTC-5).';
COMMENT ON COLUMN SMY_CENTROS.ID IS 'Identificador único y clave primaria de la tabla SMY_CENTROS.';
COMMENT ON COLUMN SMY_CENTROS.ID_ORGANIZACION IS 'Clave foránea hacia SMY_ORGANIZACIONES(ID) a la que pertenece la sede.';
COMMENT ON COLUMN SMY_CENTROS.ID_USUARIO_ULTIMA_MODIFICACION IS 'Identificador del usuario que realizó la última modificación.';
COMMENT ON COLUMN SMY_CENTROS.MANEJA_ALIMENTACION IS 'Flag por sede: Determina si esta sede específica opera el comedor y planes de alimentación (S/N).';
COMMENT ON COLUMN SMY_CENTROS.MANEJA_COSTOS_INVENTARIO IS 'Indica si la sede gestiona precios y valorización económica (S) o si opera estrictamente por cantidades físicas (N). Si es N, no se piden ni muestran precios.';
COMMENT ON COLUMN SMY_CENTROS.MANEJA_INVENTARIO IS 'Indica si esta sede geriátrica gestiona inventario físico de insumos y bodegas (S/N). Si es N, los menús y widgets permanecen ocultos.';
COMMENT ON COLUMN SMY_CENTROS.NOMBRE_CENTRO IS 'Nombre oficial de la institución o sede geriátrica.';
COMMENT ON COLUMN SMY_CENTROS.SLUG_DIRECTORIO IS 'Identificador normalizado para nombres de directorio en el servidor de archivos.';
