CREATE OR REPLACE FORCE VIEW VW_SMY_ARCHIVOS_ACTIVOS ("ID", "NOMBRE_ARCHIVO", "NOMBRE_ARCHIVO_ALMACENADO", "HASH_ARCHIVO", "NOMBRE_DIRECTORIO_BD", "RUTA_RELATIVA", "RUTA_COMPLETA_ALMACENAMIENTO", "EXTENSION", "TIPO_MIME", "TAMANO_BYTES", "TAMANO_MB", "ID_CLASE_ARCHIVO", "CODIGO_CLASE", "NOMBRE_CLASE", "ID_CENTRO", "NOMBRE_CENTRO", "SLUG_CENTRO", "ID_RESIDENTE", "NOMBRE_RESIDENTE", "CODIGO_EXPEDIENTE", "ID_ESTADO_ARCHIVO", "NOMBRE_ESTADO_ARCHIVO", "TABLA_ORIGEN", "ID_REGISTRO_ORIGEN", "FECHA_CREACION", "ID_USUARIO_ULTIMA_MODIFICACION") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT a.ID,
       a.NOMBRE_ARCHIVO,
       a.NOMBRE_ARCHIVO_ALMACENADO,
       a.HASH_ARCHIVO,
       a.NOMBRE_DIRECTORIO_BD,
       a.RUTA_RELATIVA,
       a.RUTA_COMPLETA_ALMACENAMIENTO,
       a.EXTENSION,
       a.TIPO_MIME,
       a.TAMANO_BYTES,
       ROUND(a.TAMANO_BYTES / 1048576, 2) AS TAMANO_MB,
       a.ID_CLASE_ARCHIVO,
       c.CODIGO_CLASE,
       c.NOMBRE_CLASE,
       a.ID_CENTRO,
       ce.NOMBRE_CENTRO,
       ce.SLUG_DIRECTORIO AS SLUG_CENTRO,
       a.ID_RESIDENTE,
       r.NOMBRES || ' ' || r.APELLIDOS AS NOMBRE_RESIDENTE,
       r.CODIGO_EXPEDIENTE,
       a.ID_ESTADO_ARCHIVO,
       ea.NOMBRE_ESTADO_ARCHIVO,
       a.TABLA_ORIGEN,
       a.ID_REGISTRO_ORIGEN,
       a.FECHA_CREACION,
       a.ID_USUARIO_ULTIMA_MODIFICACION
  FROM SMY_ARCHIVOS a,
       SMY_CLASES_ARCHIVOS c,
       SMY_ESTADOS_ARCHIVOS ea,
       SMY_CENTROS ce,
       SMY_RESIDENTES r
 WHERE a.ID_CLASE_ARCHIVO  = c.ID
   AND a.ID_ESTADO_ARCHIVO = ea.ID
   AND a.ID_CENTRO         = ce.ID(+)
   AND a.ID_RESIDENTE      = r.ID(+);
