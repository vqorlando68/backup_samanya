CREATE OR REPLACE FORCE VIEW V_SMY_TIMELINE_RESIDENTE ("EVENTO_ID", "ID_RESIDENTE", "TIPO_EVENTO", "TITULO", "RESUMEN", "FECHA_EVENTO", "HORA_EVENTO", "REGISTRADO_POR", "FOTO_URL", "VISIBLE_ACUDIENTE") DEFAULT COLLATION "USING_NLS_COMP"  AS 
  SELECT 
    'BITACORA-' || B.ID AS EVENTO_ID,
    B.ID_RESIDENTE,
    'bitacora' AS TIPO_EVENTO,
    'Novedad de Bitácora' AS TITULO,
    SUBSTR(DBMS_LOB.SUBSTR(B.CONTENIDO, 200, 1), 1, 200) AS RESUMEN,
    B.FECHA AS FECHA_EVENTO,
    B.HORA AS HORA_EVENTO,
    U.NOMBRE_COMPLETO AS REGISTRADO_POR,
    ARC_FOT.RUTA_COMPLETA_ALMACENAMIENTO AS FOTO_URL,
    B.VISIBLE_ACUDIENTE
FROM SMY_BITACORA_RESIDENTE B,
     SMY_USUARIOS U,
     SMY_ARCHIVOS ARC_FOT
WHERE B.ID_USUARIO = U.ID
  AND B.ID_ARCHIVO_FOTO = ARC_FOT.ID(+)
UNION ALL
SELECT 
    'SIGNOS-' || S.ID AS EVENTO_ID,
    S.ID_RESIDENTE,
    'signos_vitales' AS TIPO_EVENTO,
    'Signos Vitales' AS TITULO,
    'TA: ' || NVL(TO_CHAR(S.PRESION_SISTOLICA), '--') || '/' || NVL(TO_CHAR(S.PRESION_DIASTOLICA), '--') || ' mmHg, FC: ' || NVL(TO_CHAR(S.FRECUENCIA_CARDIACA), '--') || ' lpm, SpO2: ' || NVL(TO_CHAR(S.SATURACION_OXIGENO), '--') || '%' AS RESUMEN,
    S.FECHA AS FECHA_EVENTO,
    S.HORA AS HORA_EVENTO,
    U.NOMBRE_COMPLETO AS REGISTRADO_POR,
    NULL AS FOTO_URL,
    'S' AS VISIBLE_ACUDIENTE
FROM SMY_SIGNOS_VITALES S,
     SMY_USUARIOS U
WHERE S.ID_USUARIO_REGISTRO = U.ID
UNION ALL
SELECT 
    'MED-' || R.ID AS EVENTO_ID,
    R.ID_RESIDENTE,
    'medicacion' AS TIPO_EVENTO,
    'Medicación: ' || M.NOMBRE_MEDICAMENTO AS TITULO,
    'Dosis: ' || M.DOSIS || ' - Vía: ' || V.NOMBRE_VIA_ADMINISTRACION || ' (' || E.NOMBRE_ESTADO_ADMIN_MED || ')' AS RESUMEN,
    NVL(R.FECHA_ADMINISTRADA, R.FECHA_PROGRAMADA) AS FECHA_EVENTO,
    NVL(R.HORA_ADMINISTRADA, R.HORA_PROGRAMADA) AS HORA_EVENTO,
    NVL(U.NOMBRE_COMPLETO, 'Sistema') AS REGISTRADO_POR,
    ARC_MED.RUTA_COMPLETA_ALMACENAMIENTO AS FOTO_URL,
    'S' AS VISIBLE_ACUDIENTE
FROM SMY_REGISTROS_ADMIN_MED R,
     SMY_MEDICAMENTOS_PRESCRITOS M,
     SMY_VIAS_ADMINISTRACION V,
     SMY_ESTADOS_ADMIN_MED E,
     SMY_USUARIOS U,
     SMY_ARCHIVOS ARC_MED
WHERE R.ID_MEDICAMENTO_PRESCRITO = M.ID
  AND M.ID_VIA_ADMINISTRACION = V.ID
  AND R.ID_ESTADO_ADMIN_MED = E.ID
  AND R.ID_USUARIO_ADMINISTRO = U.ID(+)
  AND R.ID_ARCHIVO_EVIDENCIA = ARC_MED.ID(+)
UNION ALL
SELECT 
    'INC-' || I.ID AS EVENTO_ID,
    IR.ID_RESIDENTE,
    'incidente' AS TIPO_EVENTO,
    'Incidente: ' || TI.NOMBRE_TIPO_INCIDENTE AS TITULO,
    SUBSTR(DBMS_LOB.SUBSTR(I.DESCRIPCION, 200, 1), 1, 200) AS RESUMEN,
    TRUNC(I.FECHA_HORA_EVENTO) AS FECHA_EVENTO,
    TO_CHAR(I.FECHA_HORA_EVENTO, 'HH24:MI') AS HORA_EVENTO,
    U.NOMBRE_COMPLETO AS REGISTRADO_POR,
    ARC_INC.RUTA_COMPLETA_ALMACENAMIENTO AS FOTO_URL,
    I.NOTIFICADO_ACUDIENTE AS VISIBLE_ACUDIENTE
FROM SMY_INCIDENTES I,
     SMY_INCIDENTE_RESIDENTES IR,
     SMY_TIPOS_INCIDENTES TI,
     SMY_USUARIOS U,
     SMY_ARCHIVOS ARC_INC
WHERE I.ID = IR.ID_INCIDENTE
  AND I.ID_TIPO_INCIDENTE = TI.ID
  AND I.ID_USUARIO_REPORTO = U.ID
  AND I.ID_ARCHIVO_INCIDENTE = ARC_INC.ID(+)
UNION ALL
SELECT 
    'CONS-' || C.ID AS EVENTO_ID,
    C.ID_RESIDENTE,
    'consentimiento' AS TIPO_EVENTO,
    'Consentimiento: ' || TC.NOMBRE_TIPO_CONSENTIMIENTO AS TITULO,
    SUBSTR(DBMS_LOB.SUBSTR(C.DESCRIPCION, 200, 1), 1, 200) AS RESUMEN,
    C.FECHA_ENVIO AS FECHA_EVENTO,
    '08:00' AS HORA_EVENTO,
    U.NOMBRE_COMPLETO AS REGISTRADO_POR,
    ARC_CONS.RUTA_COMPLETA_ALMACENAMIENTO AS FOTO_URL,
    'S' AS VISIBLE_ACUDIENTE
FROM SMY_CONSENTIMIENTOS C,
     SMY_TIPOS_CONSENTIMIENTOS TC,
     SMY_USUARIOS U,
     SMY_ARCHIVOS ARC_CONS
WHERE C.ID_TIPO_CONSENTIMIENTO = TC.ID
  AND C.ID_USUARIO_CREADOR = U.ID
  AND C.ID_ARCHIVO_CONSENTIMIENTO = ARC_CONS.ID(+);
